import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const fixture = path.join('.wrangler', 'build-v2-acceptance');
const run = spawnSync(process.execPath, ['scripts/prepare-deploy.mjs'], { encoding: 'utf8', env: { ...process.env, SMARTTOOLS_OUTPUT_DIR: fixture } });
assert.equal(run.status, 0, run.stderr);
const files = await readdir(fixture);
assert.deepEqual(files, ['_routes.json']);
assert.deepEqual(JSON.parse(await readFile(path.join(fixture, '_routes.json'), 'utf8')), { version:1, include:['/*'], exclude:[] });
const denied = spawnSync(process.execPath, ['scripts/prepare-deploy.mjs'], { encoding:'utf8', env: { ...process.env, SMARTTOOLS_OUTPUT_DIR: path.resolve(process.cwd(), '..', 'outside-build') } });
assert.notEqual(denied.status, 0);
console.log('PASS API-only build and output guard');
